"""Build an episode's timing from its cues and its measured audio.

    python make_timing.py --episode 1

Reads epN/outline.json, epN/cues.json and epN/audio_manifest.json (written
by make_voices.py) and writes epN/timing.json: the first frame and length,
in 30 fps frames, of every scene, beat, step and dialogue line of the
episode body (scenes s01 to the last scene before s99).  Frames count from
the first frame of s01; 'body_offset_frames' is where s01 starts in the
assembled episode, after the titles (s00).

Line steps last as long as their audio plus a gap (cues.json 'gaps'): a
short one when the same kitten speaks next, a longer one at a change of
speaker, the longest after a beat's last line.  Every scene after the
first opens with a transition (cues.json 'scene_transition_seconds'), and
the body ends with one.  Do, pause and hold steps last as long as the cues
say; a recap_montage of 'more_losses' lasts as long as the game engine's
game takes at its seconds_per_move.
"""
import argparse
import json
import math
from pathlib import Path

from cue_tools import steps, step_visuals, split_visual, visual_params, montage_games

HERE = Path(__file__).resolve().parent
FPS = 30
MONTAGE_STUCK_SECONDS = 1.6     # Pascal's dead end, before the tally mark
MONTAGE_RESET_SECONDS = 0.8     # the cards go back to the 45-hand


def load(name):
    return json.loads((HERE / name).read_text(encoding="utf-8"))


def frames(seconds):
    return int(math.ceil(seconds * FPS - 1e-9))


def montage_seconds(step, objects):
    for v in step_visuals(step):
        verb, arg = split_visual(v)
        if verb == "recap_montage" and arg == "more_losses":
            p = visual_params(v)
            tries = objects["tries:complement_1to6"]
            x = tries["tries"][p["game"]]
            reply = x["replies"][(0, 3)[p["game"]]]["move"]
            seq = montage_games(objects["hand:complement_1to6"]["cards"],
                                [(tuple(x["move"]), tuple(reply))])[0]
            moves = sum(1 for _, m, _ in seq if m)
            return moves * p.get("seconds_per_move", 0.85) + MONTAGE_STUCK_SECONDS + MONTAGE_RESET_SECONDS
    raise ValueError("seconds 'montage' needs a recap_montage:more_losses visual")


def build(n):
    outline = load(f"ep{n}/outline.json")
    cues = load(f"ep{n}/cues.json")
    manifest = load(f"ep{n}/audio_manifest.json")["lines"]
    objects = load("math_objects.json")["objects"]
    gaps = cues["gaps"]
    trans = frames(cues.get("scene_transition_seconds", 1.2))
    body = [s for s in outline["scenes"] if s.get("kind") not in ("title_card", "end_credits")]
    title = next(s for s in outline["scenes"] if s.get("kind") == "title_card")

    t = 0
    out_scenes, out_beats, out_lines = {}, {}, {}
    for si, scene in enumerate(body):
        s0 = t
        t += trans                       # transition into the scene
        for beat in scene["beats"]:
            b0 = t
            st = steps(cues, beat["id"])
            rows = []
            for k, s in enumerate(st):
                if "line" in s:
                    lid = s["line"]
                    audio = manifest[lid]["seconds"]
                    nxt = st[k + 1] if k + 1 < len(st) else None
                    if nxt is None:
                        gap = gaps["beat_end"]
                    elif "line" in nxt and manifest[nxt["line"]]["speaker"] == manifest[lid]["speaker"]:
                        gap = gaps["same_speaker"]
                    elif "line" in nxt:
                        gap = gaps["new_speaker"]
                    else:
                        gap = gaps["same_speaker"]
                    n_f = frames(audio + gap)
                    out_lines[lid] = {"start": t, "frames": n_f, "audio_frames": frames(audio),
                                      "speaker": manifest[lid]["speaker"]}
                    rows.append({"kind": "line", "line": lid, "start": t, "frames": n_f})
                else:
                    kind = next(x for x in ("do", "pause", "hold") if x in s)
                    sec = s.get("seconds", s.get("hold"))
                    if sec == "montage":
                        sec = montage_seconds(s, objects)
                    n_f = frames(float(sec))
                    rows.append({"kind": kind, "start": t, "frames": n_f})
                t += n_f
            out_beats[beat["id"]] = {"scene": scene["id"], "start": b0, "frames": t - b0, "steps": rows}
        if si == len(body) - 1:
            t += trans                   # transition out of the body
        out_scenes[scene["id"]] = {"start": s0, "frames": t - s0, "seconds": round((t - s0) / FPS, 3)}
    title_frames = round(title["target_seconds"] * FPS)
    credits = next(s for s in outline["scenes"] if s.get("kind") == "end_credits")
    return {
        "_about": [
            "Generated by make_timing.py from cues.json and audio_manifest.json; do not edit by hand.",
            "Frames are 30 fps and count from the first frame of s01.",
        ],
        "episode": n,
        "fps": FPS,
        "body_offset_frames": title_frames,
        "transition_frames": trans,
        "body_frames": t,
        "frames": title_frames + t + round(credits["target_seconds"] * FPS),
        "scenes": out_scenes,
        "beats": out_beats,
        "lines": out_lines,
    }


def main():
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("--episode", type=int, default=1)
    args = ap.parse_args()
    n = args.episode
    timing = build(n)
    text = json.dumps(timing, indent=1)
    (HERE / f"ep{n}" / "timing.json").write_text(text + "\n", encoding="utf-8")
    outline = load(f"ep{n}/outline.json")
    print(f"{'scene':6} {'measured':>9} {'target':>7}")
    for s in outline["scenes"]:
        m = timing["scenes"].get(s["id"])
        sec = m["seconds"] if m else s["target_seconds"]
        print(f"{s['id']:6} {sec:9.1f} {s['target_seconds']:7.1f}")
    print(f"total  {timing['frames'] / FPS:9.1f} {sum(s['target_seconds'] for s in outline['scenes']):7.1f}")


if __name__ == "__main__":
    main()
