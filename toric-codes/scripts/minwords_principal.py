"""List the minimum-weight words of the [49,11,28]_8 code and describe their zero sets.
License: MIT."""
import sys, os, subprocess, itertools, json
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from gf import GF
from toric import lattice_points, residues, gen_matrix, torus_points, MINDIST
q = 8; m = 7; F = GF(q)
U = residues(lattice_points([(5,-1),(-1,5),(-1,-1)],[0,0,5]), q)
rows = gen_matrix(U, q, 2, F)
pts = torus_points(q)
lines = [f"list {q} 49 {len(rows)}"]
lines += [" ".join(str(F.add(a,b)) for b in range(q)) for a in range(q)]
lines += [" ".join(str(F.mul(a,b)) for b in range(q)) for a in range(q)]
lines += [" ".join(map(str, r)) for r in rows]
lines.append("28 7")
out = subprocess.run([MINDIST], input="\n".join(lines)+"\n", capture_output=True, text=True).stdout
words = set()
for line in out.splitlines():
    if line.startswith("word"):
        v = list(map(int, line.split()[1:]))
        lead = next(x for x in v if x)
        il = F.inv(lead)
        words.add(tuple(F.mul(il, x) for x in v))
print("projective minimum-weight words:", len(words), "(x7 =", 7*len(words), "words)")
zsets = [frozenset(i for i, x in enumerate(w) if x == 0) for w in words]
print("distinct zero sets:", len(set(zsets)))
# classify zero sets: union of 3 parallel 'lines' (cosets of 1-dim subtori) in some direction?
def coset_lines(direction):
    # cosets of the subgroup generated by direction in (Z/7)^2, as index sets
    a, b = direction
    cos = {}
    for idx, (i, j) in enumerate(pts):
        # invariant: the linear form orthogonal to direction
        key = (b * i - a * j) % m
        cos.setdefault(key, set()).add(idx)
    return [frozenset(s) for s in cos.values()]
dirs = [(1,0),(0,1)] + [(1,k) for k in range(1,7)]
kinds = {}
for Z in set(zsets):
    found = None
    for dvec in dirs:
        L = coset_lines(dvec)
        inside = [l for l in L if l <= Z]
        if sum(len(l) for l in inside) == len(Z):
            found = (dvec, len(inside)); break
    kinds.setdefault(found, 0); kinds[found] += 1
print("zero-set types (direction of the parallel lines, number of lines) -> count:")
for k, v in sorted(kinds.items(), key=lambda kv: str(kv[0])): print("  ", k, v)
json.dump(sorted([sorted(z) for z in set(zsets)]), open("minwords_principal.json","w"))
